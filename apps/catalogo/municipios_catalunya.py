def cargar_municipios(Ciudad, Comarca):
    """
    Crea los municipios que falten enlazados a su comarca. No borra ni duplica
    (compara sin mayúsculas). Las comarcas tienen que existir antes (migración 0003).
    """
    comarcas = {c.nombre.lower(): c for c in Comarca.objects.all()}
    existentes = {n.lower() for n in Ciudad.objects.values_list('nombre', flat=True)}
    nuevas = [
        Ciudad(nombre=nombre, comarca=comarcas.get(comarca.lower()))
        for nombre, comarca in MUNICIPIOS_CATALUNYA
        if nombre.lower() not in existentes
    ]
    Ciudad.objects.bulk_create(nuevas)
